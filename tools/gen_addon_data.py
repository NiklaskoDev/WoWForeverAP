"""Generates the addon's data tables from the apworld CSVs, so the addon never carries hand-copied data.

    python tools/gen_addon_data.py           write the generated files
    python tools/gen_addon_data.py --check   exit 1 when a generated file is out of date (CI)

Outputs:
  addon/WoWForeverAP/Data/Generated.lua   ns.Data: zones, quests, professions, tiers, fillers, care package, goal
  addon/spec/fixtures/ids.lua             id cases computed by ids.py, which the Lua spec compares against Ids.lua
  addon/spec/fixtures/inbox_from_client.lua  an Inbox.lua exactly as the client writes it, which the Lua spec loads
"""
import argparse
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

from _apworld import ROOT, apworld_module

data_loader = apworld_module("data_loader")
ids = apworld_module("ids")
inbox = apworld_module("client.inbox")
lua_table = apworld_module("client.lua_table")

GENERATED_FILE = ROOT / "addon" / "WoWForeverAP" / "Data" / "Generated.lua"
IDS_FIXTURE_FILE = ROOT / "addon" / "spec" / "fixtures" / "ids.lua"
INBOX_FIXTURE_FILE = ROOT / "addon" / "spec" / "fixtures" / "inbox_from_client.lua"
HEADER = "-- Generated by tools/gen_addon_data.py from apworld/wow_forever/data/*.csv. Do not edit by hand.\n"
PLACEHOLDER = "GENERATED"

# Natives that must round-trip: the edges of the range and values seen in real data.
SAMPLE_NATIVES = (0, 1, 783, 1429, ids.CATEGORY_SIZE - 1)


def _table_as_expression(value: object, prefix: str) -> str:
    """Render a value with the shared Lua serialiser and strip the ``NAME = `` it puts in front."""
    rendered = lua_table.render(PLACEHOLDER, value)
    return prefix + rendered.removeprefix(f"{PLACEHOLDER} = ")


def build_generated(data: "data_loader.GameData") -> str:
    """Text of ``Data/Generated.lua`` for the given game data."""
    tables = {
        "levelGoal": data_loader.GOAL_LEVEL,
        "zones": {
            zone.ui_map_id: {"name": zone.name, "min": zone.min_level, "max": zone.max_level,
                             "faction": zone.faction, "release": zone.release}
            for zone in data.zones
        },
        "quests": {quest.quest_id: quest.zone_ui_map_id for quest in data.quests},
        "professions": {
            profession.skill_line_id: {"key": profession.key, "name": profession.name,
                                       "kind": profession.kind, "release": profession.release}
            for profession in data.professions
        },
        "tiers": [
            {"name": tier.name, "maxSkill": tier.max_skill, "requiredLevel": tier.required_level,
             "release": tier.release}
            for tier in data.profession_tiers
        ],
        "fillers": {item.native_id: {"name": item.name, "release": item.release}
                    for item in data.misc_items if item.kind == "filler"},
        "carePackageItemId": ids.item_id(data.care_package.category, data.care_package.native_id),
    }
    return HEADER + "local _, ns = ...\n" + _table_as_expression(tables, "ns.Data = ")


def build_ids_fixture() -> str:
    """Text of ``spec/fixtures/ids.lua``: ids computed by Python for every category and sample native."""
    cases = []
    for kind, categories, build in (("location", ids.LocCat, ids.location_id), ("item", ids.ItemCat, ids.item_id)):
        for category in categories:
            for native in SAMPLE_NATIVES:
                cases.append({"kind": kind, "category": int(category), "native": native,
                              "id": build(category, native)})
    constants = {
        "base": ids.BASE,
        "categorySize": ids.CATEGORY_SIZE,
        "professionSkill": {"skillLineId": 171, "skill": 75, "native": ids.profession_skill_native(171, 75)},
    }
    return (HEADER + "return " + lua_table.render(PLACEHOLDER, {"constants": constants, "cases": cases})
            .removeprefix(f"{PLACEHOLDER} = "))


def build_inbox_fixture() -> str:
    """An ``Inbox.lua`` written by the client's own writer for a small made-up slot."""
    slot_data = {"schema": 1, "world_version": "0.0.0", "faction": "alliance", "start_zone": 1429,
                 "content_release": 1, "goal_level": 60, "professions": [171, 186], "level_step": 1,
                 "profession_step": 25,
                 "economy": {"auctionHouse": True, "trading": True, "mail": False, "sharedBanks": False,
                             "mainBoosts": False, "carePackages": 5, "carePackageGold": 50,
                             "carePackageStacks": 5}}
    quest = ids.location_id(ids.LocCat.QUEST, 783)
    levels = [ids.location_id(ids.LocCat.LEVEL, level) for level in (2, 3)]
    skill = ids.location_id(ids.LocCat.PROFESSION_SKILL, ids.profession_skill_native(171, 25))
    received = [
        SimpleNamespace(item=ids.item_id(ids.ItemCat.ZONE, 1436), location=quest, player=1),
        SimpleNamespace(item=ids.item_id(ids.ItemCat.PROFESSION_TIER, 171), location=levels[0], player=2),
    ]
    hints = [
        inbox.hint_entry("Progressive Alchemy", ids.item_id(ids.ItemCat.PROFESSION_TIER, 171), 'Chest "A"',
                         "Ben", 'Anna "The Tank"', False, True),
        inbox.hint_entry("Sword", 900, "Quest 7", 'Anna "The Tank"', "Ben", True, False),
    ]
    slot_dict = inbox.build("AP_1234:Wow", "AP_1234", "Wow", slot_data, [quest, *levels, skill], [levels[0]],
                            received, {1: 'Anna "The Tank"', 2: "Ben"}, hints)
    with tempfile.TemporaryDirectory() as folder:
        (Path(folder) / inbox.INBOX_ADDON_FOLDER).mkdir(parents=True)
        written = inbox.write(Path(folder), "AP_1234:Wow", slot_dict, now=lambda: 1763380000)
        return written.read_text(encoding="utf-8")


def display_path(path: Path) -> str:
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def expected_outputs() -> dict[Path, str]:
    """Every generated file with the text it must have."""
    return {
        GENERATED_FILE: build_generated(data_loader.load_game_data()),
        IDS_FIXTURE_FILE: build_ids_fixture(),
        INBOX_FIXTURE_FILE: build_inbox_fixture(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when a file is out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, text in expected_outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    names = ", ".join(display_path(path) for path in stale)
    if args.check and stale:
        print(f"out of date: {names}\nrun: python tools/gen_addon_data.py", file=sys.stderr)
        return 1
    print(f"updated: {names}" if stale else "generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
