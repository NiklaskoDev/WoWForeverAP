class GuideMarkerError(ValueError):
    """The game guide lacks its generated-section markers, or has them more than once or in the wrong order."""


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(value) for value in row) + " |" for row in rows]
    return lines


def build_guide_section(data: "data_loader.GameData") -> str:
    """The generated "Item reference" section of the game guide, without the markers."""
    release_label = {release.id: release.label for release in data.releases}
    zone_rows = [
        (zone.item_name, descriptions.FACTION_LABELS[zone.faction], f"{zone.min_level}-{zone.max_level}",
         "yes" if zone.is_start else "",
         descriptions.join_words([i.name for i in descriptions.zone_instances(data, zone)]),
         release_label[zone.release])
        for zone in data.zones
    ]
    tiers = sorted(data.profession_tiers, key=lambda tier: tier.tier)
    rank_rows = [
        (str(tier.tier), tier.name, str(tier.max_skill), str(tier.required_level),
         str(descriptions.tier_logic_level(data, tier) or "-"), release_label[tier.release])
        for tier in tiers
    ]
    profession_rows = [(p.item_name, p.kind, descriptions.materials_summary(data, p)) for p in data.professions]
    other_rows = [(item.name, descriptions.misc_item_description(data, item)) for item in data.misc_items]
    lines = [
        'Generated from the game data, like the item descriptions of this world. The data is provisional (see '
        '"Unconfirmed content").',
        "",
        "### Zones",
        "",
        "Each zone is one item, `Zone: <zone>`. Once it has arrived you may quest, kill for experience, gather and "
        "loot in the zone; before that, only travel through it.",
        "",
        *_table(("Item", "Faction", "Levels", "Start zone", "Dungeons", "Release"), zone_rows),
        "",
        "### Professions",
        "",
        "Each profession is one item, `Progressive <profession>`, with one copy per rank. Do not train a rank "
        "before its copy has arrived. Every profession has the same ranks:",
        "",
        *_table(("Copies", "Rank", "Skill cap", "Trainer level", "Logic level", "Release"), rank_rows),
        "",
        "The logic level is the character level the logic needs for skill checks up to the rank's cap. A seed whose "
        "goal_level is below it leaves that rank and every later one out.",
        "",
        *_table(("Item", "Kind", "Self-found materials"), profession_rows),
        "",
        '"Self-found" means the Auction House, trading, mail and shared banks are all off.',
        "",
        "### Other items",
        "",
        *_table(("Item", "Description"), other_rows),
    ]
    return "\n".join(lines)


def splice_guide(current: str, section: str) -> str:
    """``current`` with the text between the markers replaced by ``section``; everything else is unchanged."""
    where = display_path(GUIDE_FILE)
    begin, end = current.find(GUIDE_BEGIN), current.find(GUIDE_END)
    if begin < 0 or end < 0:
        raise GuideMarkerError(f"{where} must contain the markers {GUIDE_BEGIN} and {GUIDE_END}")
    if current.count(GUIDE_BEGIN) != 1 or current.count(GUIDE_END) != 1:
        raise GuideMarkerError(f"{where} must contain each generated-section marker exactly once")
    if end < begin:
        raise GuideMarkerError(f"{where}: the END marker comes before the BEGIN marker")
    # Blank lines around the section keep the markdown renderer from folding a table into a marker line.
    return current[:begin + len(GUIDE_BEGIN)] + "\n\n" + section + "\n\n" + current[end:]


def display_path(path: Path) -> str:
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def expected_outputs() -> dict[Path, str]:
    """Every generated file with the text it must have."""
    data = data_loader.load_game_data()
    if not GUIDE_FILE.exists():
        raise GuideMarkerError(f"{display_path(GUIDE_FILE)} is missing")
    guide = splice_guide(GUIDE_FILE.read_text(encoding="utf-8"), build_guide_section(data))
    return {
        GENERATED_FILE: build_generated(data),
        IDS_FIXTURE_FILE: build_ids_fixture(),
        INBOX_FIXTURE_FILE: build_inbox_fixture(),
        GUIDE_FILE: guide,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when a file is out of date")
    args = parser.parse_args(argv)
    try:
        outputs = expected_outputs()
    except GuideMarkerError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    names = ", ".join(display_path(path) for path in stale)
    if args.check and stale:
        print(f"out of date: {names}\nrun: python tools/gen_addon_data.py", file=sys.stderr)
        return 1
    print(f"updated: {names}" if stale else "generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
