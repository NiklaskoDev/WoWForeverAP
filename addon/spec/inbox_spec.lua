local Env = require("helpers.addon_env")

describe("Inbox", function()
    local ns, Inbox

    before_each(function()
        ns = Env.new({ "Core/Namespace.lua", "Core/Inbox.lua" })
        Inbox = ns.Inbox
    end)

    it("accepts the layout of schema 1", function()
        assert.is_true(Inbox.validate({ schema = 1, slots = {} }))
    end)

    it("rejects missing, malformed and foreign-schema inboxes", function()
        for _, bad in ipairs({ { schema = 2, slots = {} }, { schema = 1 }, { slots = {} } }) do
            local ok, errorKey = Inbox.validate(bad)
            assert.is_false(ok)
            assert.equals("INBOX_INVALID", errorKey)
        end
        assert.is_false(Inbox.validate(nil))
        assert.is_false(Inbox.validate("text"))
    end)

    it("lists slot keys sorted and skips entries that are not slot tables", function()
        local inbox = { schema = 1, slots = { ["b:Two"] = {}, ["a:One"] = {}, ["c:Bad"] = true, [5] = {} } }
        assert.same({ "a:One", "b:Two" }, Inbox.slotKeys(inbox))
        assert.same({}, Inbox.slotKeys(nil))
        assert.same({}, Inbox.slotKeys({ schema = 9, slots = { x = {} } }))
    end)

    it("finds a slot by key only in a valid inbox", function()
        local inbox = Env.inbox()
        assert.equals(inbox.slots["S1:Wow"], Inbox.slot(inbox, "S1:Wow"))
        assert.is_nil(Inbox.slot(inbox, "missing"))
        assert.is_nil(Inbox.slot({ schema = 7, slots = inbox.slots }, "S1:Wow"))
    end)

    it("knows which locations are in the seed and which are checked", function()
        local slot = Env.inbox({ locations = { [10] = true, [11] = true }, checked = { [11] = true } }).slots["S1:Wow"]
        assert.is_true(Inbox.isLocationInSeed(slot, 10))
        assert.is_false(Inbox.isLocationInSeed(slot, 12))
        assert.is_false(Inbox.isChecked(slot, 10))
        assert.is_true(Inbox.isChecked(slot, 11))
    end)

    it("tolerates a slot without tables", function()
        local slot = {}
        assert.is_false(Inbox.isLocationInSeed(slot, 1))
        assert.is_false(Inbox.isChecked(slot, 1))
        assert.same({}, Inbox.checkedSet(slot))
        assert.same({}, Inbox.options(slot))
        assert.same({ locations = 0, checked = 0, open = 0, items = 0 }, Inbox.counts(slot))
    end)

    it("counts items per id in received order", function()
        local slot = { items = { { id = 7, sender = "A", loc = 1 }, { id = 8 }, { id = 7 } } }
        assert.equals(2, Inbox.countItem(slot, 7))
        assert.is_true(Inbox.hasItem(slot, 8))
        assert.is_false(Inbox.hasItem(slot, 9))
        assert.equals(3, #Inbox.items(slot))
    end)

    it("counts total, checked and open locations", function()
        local slot = { locations = { [1] = true, [2] = true, [3] = true }, checked = { [2] = true, [99] = true },
                       items = { { id = 1 } } }
        assert.same({ locations = 3, checked = 1, open = 2, items = 1 }, Inbox.counts(slot))
    end)

    describe("hints and age", function()
        it("returns the hints the client wrote and an empty list for an inbox without any", function()
            local hints = { { item = "Zone: Dun Morogh", found = false } }
            assert.equals(hints, Inbox.hints({ hints = hints }))
            assert.same({}, Inbox.hints({}))
            assert.same({}, Inbox.hints({ hints = "garbage" }))
        end)

        it("returns the time the inbox was written when it is a number", function()
            assert.equals(1763380000, Inbox.written({ written = 1763380000 }))
            assert.is_nil(Inbox.written({}))
            assert.is_nil(Inbox.written({ written = "now" }))
            assert.is_nil(Inbox.written(nil))
        end)
    end)
end)

describe("Inbox written by the Python client", function()
    local ns, slotKey, slot

    before_each(function()
        ns = Env.new()
        dofile(Env.SPEC_DIR .. "fixtures/inbox_from_client.lua") -- generated by tools/gen_addon_data.py
        slotKey = "AP_1234:Wow"
        slot = ns.Inbox.slot(ns.Inbox.current(), slotKey)
    end)

    it("is accepted and its slot is found", function()
        assert.is_true(ns.Inbox.validate(ns.Inbox.current()))
        assert.same({ slotKey }, ns.Inbox.slotKeys(ns.Inbox.current()))
        assert.is_table(slot)
    end)

    it("answers location, checked and count questions with the ids the addon builds", function()
        local quest = ns.Ids.locationId(ns.Ids.LocCat.QUEST, 783)
        local level2 = ns.Ids.locationId(ns.Ids.LocCat.LEVEL, 2)
        assert.is_true(ns.Inbox.isLocationInSeed(slot, quest))
        assert.is_false(ns.Inbox.isChecked(slot, quest))
        assert.is_true(ns.Inbox.isChecked(slot, level2))
        assert.same({ locations = 4, checked = 1, open = 3, items = 2 }, ns.Inbox.counts(slot))
        assert.equals(60, ns.Level.goalLevel(slot))
        assert.same({ 2, 3 }, ns.Level.milestones(slot, 1, 5)) -- checked ones are filtered later, by the Tracker
    end)

    it("reads the options the client wrote", function()
        local options = ns.Inbox.options(slot)
        assert.equals("alliance", options.faction)
        assert.same({ 171, 186 }, options.professions)
        assert.equals(1429, options.startZone)
    end)

    it("names the received items, including a sender name with quotes", function()
        assert.same({
            'Zone: Westfall (from Anna "The Tank")',
            "Progressive Alchemy (tier 1) (from Ben)",
        }, ns.Names.itemLines(ns.Inbox.items(slot), 1, 2))
    end)

    it("lets a matching character link to it", function()
        local db = ns.DB.init(nil)
        ns.DB.touchCharacter(db, "Player-1", "Arthas", "Alliance", "PALADIN")
        assert.is_true(ns.Link.link(db, "Player-1", slotKey, ns.Inbox.current(), 1, {}, 1))
    end)
end)
